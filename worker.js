function withAgentJsonHeaders(source) {
  const headers = new Headers(source.headers);
  headers.set("Content-Type", "application/json; charset=utf-8");
  headers.set("Cache-Control", "public, max-age=300");
  headers.set("Vary", "Accept");
  headers.set("X-Content-Type-Options", "nosniff");
  headers.set("Referrer-Policy", "strict-origin-when-cross-origin");
  headers.set("Permissions-Policy", "camera=(), microphone=(), geolocation=(), payment=(), usb=()");
  headers.set("X-Frame-Options", "DENY");
  headers.set(
    "Content-Security-Policy",
    "default-src 'self'; base-uri 'self'; object-src 'none'; frame-ancestors 'none'; img-src 'self' data: blob:; font-src 'self'; style-src 'self' 'unsafe-inline'; script-src 'self'; connect-src 'self'; form-action 'self' mailto:; upgrade-insecure-requests"
  );
  headers.set("Strict-Transport-Security", "max-age=31536000; includeSubDomains; preload");
  headers.delete("Content-Length");
  headers.delete("Content-Encoding");
  headers.delete("ETag");
  headers.delete("Last-Modified");
  return headers;
}

function wantsMarkdown(request) {
  const accept = request.headers.get("Accept") || "";
  return /(?:^|,|;)\s*text\/markdown(?:\s*[;,]|$)/i.test(accept);
}

function withMarkdownHeaders(source, markdown) {
  const headers = new Headers(source.headers);

  // _headers applies to static asset responses, not responses created by
  // this Worker. Keep the same security policy on the Markdown variant.
  headers.set("X-Content-Type-Options", "nosniff");
  headers.set("Referrer-Policy", "strict-origin-when-cross-origin");
  headers.set("Permissions-Policy", "camera=(), microphone=(), geolocation=(), payment=(), usb=()");
  headers.set("X-Frame-Options", "DENY");
  headers.set(
    "Content-Security-Policy",
    "default-src 'self'; base-uri 'self'; object-src 'none'; frame-ancestors 'none'; img-src 'self' data: blob:; font-src 'self'; style-src 'self' 'unsafe-inline'; script-src 'self'; connect-src 'self'; form-action 'self' mailto:; upgrade-insecure-requests"
  );
  headers.set(
    "Strict-Transport-Security",
    "max-age=31536000; includeSubDomains; preload"
  );
  headers.set("Content-Type", "text/markdown; charset=utf-8");
  headers.set("Vary", "Accept");
  headers.set("Content-Signal", "ai-train=no, search=yes, ai-input=yes");
  headers.set("X-Markdown-Tokens", String(Math.ceil(markdown.length / 4)));
  headers.set("X-Original-Tokens", String(Math.ceil(markdown.length / 3)));
  headers.delete("Content-Encoding");
  headers.delete("Content-Length");
  headers.delete("Content-Range");
  headers.delete("Transfer-Encoding");
  headers.delete("ETag");
  headers.delete("Last-Modified");
  return headers;
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);

    const redirects = {
      "/about.html": "/about",
      "/contact.html": "/contact",
      "/privacy.html": "/privacy",
      "/terms.html": "/terms"
    };

    const redirectTarget = redirects[url.pathname];
    if (redirectTarget) {
      return Response.redirect(new URL(redirectTarget, url).toString(), 301);
    }

    // Explicit machine-readable homepage view. This describes only public,
    // implemented capabilities and does not imply that a product API exists.
    if (
      (request.method === "GET" || request.method === "HEAD") &&
      url.pathname === "/" &&
      url.searchParams.get("mode") === "agent"
    ) {
      const assetResponse = await env.ASSETS.fetch(new Request(new URL("/", url.origin), { method: "GET" }));
      const body = request.method === "HEAD" ? null : JSON.stringify(AGENT_VIEW, null, 2);
      return new Response(body, {
        status: 200,
        headers: withAgentJsonHeaders(assetResponse)
      });
    }

    // Only serve Markdown for read requests. Other methods must reach the
    // static asset handler unchanged.
    const key = url.pathname === "/" ? "/" : url.pathname.replace(/\/$/, "");

    if (request.method === "GET" && wantsMarkdown(request) && MARKDOWN_PAGES[key]) {
      // Markdown content is generated by this Worker; the asset request is
      // only used to inherit the shared response/security headers.
      const assetResponse = await env.ASSETS.fetch(new Request(url.toString(), { method: "GET" }));
      const markdown = MARKDOWN_PAGES[key];
      // A mapped Markdown page is generated by this Worker, so its status
      // must not depend on whether an extensionless static asset exists.
      return new Response(markdown, {
        status: 200,
        headers: withMarkdownHeaders(assetResponse, markdown)
      });
    }

    const assetResponse = await env.ASSETS.fetch(request);

    // Agent-friendly 404: preserve the real not-found status while returning
    // a useful Markdown explanation to clients that explicitly request it.
    if (request.method === "GET" && wantsMarkdown(request) && assetResponse.status === 404) {
      const markdown = [
        "# Page not found",
        "",
        "The requested page does not exist on Burion Studio.",
        "",
        "You can explore the site's public overview and available pages here:",
        "",
        "- [Site overview (llms.txt)](https://burionstudio.com/llms.txt)",
        "- [XML sitemap](https://burionstudio.com/sitemap.xml)"
      ].join("\n");

      return new Response(markdown, {
        status: 404,
        headers: withMarkdownHeaders(assetResponse, markdown)
      });
    }

    return assetResponse;
  }
};
